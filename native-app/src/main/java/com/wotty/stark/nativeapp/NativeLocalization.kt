private val nativeDeviceDefaultLocale = Locale.getDefault()

internal enum class NativeLanguageChoice { SYSTEM, ZH_CN, EN_US }
internal enum class NativeFontChoice(val scale: Float) { SMALL(0.9f), STANDARD(1.0f), LARGE(1.15f) }
internal data class NativeUiSettings(val language: NativeLanguageChoice, val font: NativeFontChoice)

internal class NativeUiPreferences(context: Context) {
    private val storage = context.getSharedPreferences("native-ui-preferences", Context.MODE_PRIVATE)
    var value by mutableStateOf(read())
        private set

    private fun read(): NativeUiSettings = NativeUiSettings(
        language = NativeLanguageChoice.values().firstOrNull { it.name == storage.getString("language", "ZH_CN") } ?: NativeLanguageChoice.ZH_CN,
        font = NativeFontChoice.values().firstOrNull { it.name == storage.getString("font", "STANDARD") } ?: NativeFontChoice.STANDARD,
    )

    fun selectLanguage(language: NativeLanguageChoice) = update(value.copy(language = language))
    fun selectFont(font: NativeFontChoice) = update(value.copy(font = font))

    private fun update(next: NativeUiSettings) {
        value = next
        storage.edit().putString("language", next.language.name).putString("font", next.font.name).apply()
    }
}

internal val LocalNativeUiPreferences = staticCompositionLocalOf<NativeUiPreferences> { error("Native UI preferences are not provided") }

internal fun nativeFontDensity(base: Density, font: NativeFontChoice): Density = Density(base.density, base.fontScale * font.scale)

internal fun nativeLocalizedContext(context: Context, language: NativeLanguageChoice): Context {
    val locale = nativeLocaleFor(language) ?: return context
    val configuration = Configuration(context.resources.configuration).apply {
        setLocale(locale)
        setLayoutDirection(locale)
    }
    return ContextThemeWrapper(context, 0).apply { applyOverrideConfiguration(configuration) }
}

internal fun applyNativeProcessLocale(language: NativeLanguageChoice) {
    Locale.setDefault(nativeLocaleFor(language) ?: nativeDeviceDefaultLocale)
}

private fun nativeLocaleFor(language: NativeLanguageChoice): Locale? = when (language) {
    NativeLanguageChoice.SYSTEM -> null
    NativeLanguageChoice.ZH_CN -> Locale.SIMPLIFIED_CHINESE
    NativeLanguageChoice.EN_US -> Locale.US
}

