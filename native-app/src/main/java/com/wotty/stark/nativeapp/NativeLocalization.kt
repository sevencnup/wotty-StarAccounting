private val nativeReplacementToken = Regex("\\$(\\d+)")

internal fun translateNativeText(value: String, language: NativeLanguageChoice): String {
    if (!nativeUsesEnglish(language)) return value
    nativeWebTranslations[value]?.let { return it }
    nativeExtraTranslations[value]?.let { return it }
    nativeCallbackTranslations.firstNotNullOfOrNull { entry ->
        entry.pattern.matchEntire(value)?.let(entry.render)
    }?.let { return it }
    nativePatternTranslations.firstNotNullOfOrNull { entry ->
        val match = entry.pattern.matchEntire(value) ?: return@firstNotNullOfOrNull null
        nativeReplacementToken.replace(entry.replacement) { token ->
            match.groupValues.getOrElse(token.groupValues[1].toInt()) { token.value }
        }
    }?.let { return it }
    if (" · " in value) return value.split(" · ").joinToString(" · ") { translateNativeText(it, NativeLanguageChoice.EN_US) }
    if (value.trimEnd().endsWith("›")) {
        val base = value.trimEnd().dropLast(1).trimEnd()
        val translatedBase = translateNativeText(base, NativeLanguageChoice.EN_US)
        if (translatedBase != base) return translatedBase + value.substring(base.length)
    }
    return value
}

private fun nativeEnglishMonth(rawMonth: String): String {
    val month = rawMonth.toIntOrNull() ?: return rawMonth
    return listOf("January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December")
        .getOrNull(month - 1) ?: "$month month"
}

private fun nativeUsesEnglish(language: NativeLanguageChoice): Boolean = when (language) {
    NativeLanguageChoice.EN_US -> true
    NativeLanguageChoice.ZH_CN -> false
    NativeLanguageChoice.SYSTEM -> nativeDeviceDefaultLocale.language.startsWith("en", ignoreCase = true)
}

